"""Keep original dimensions; losslessly compress PNGs and add smaller delivery copies.

AVIF is high-quality lossy compression, never a pixel-exact master replacement.
Only keep alternatives at least 8% smaller and with decoded RGB PSNR >= 40 dB.
Existing WebP/JPEG fallbacks and image attribution remain available.
"""
import hashlib
import io
import json
import math
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / 'dashboard/static'
BACKUP = ROOT / 'output/image-optimization-backup'
(ROOT / 'output').mkdir(exist_ok=True)
report = {'png': [], 'delivery': [], 'unchanged': []}

# Only alter PNG bitstreams losslessly. Hash identical copies to avoid repeated work.
optimized = {}
for folder in (STATIC, ROOT / 'uploads'):
    for path in folder.rglob('*.png'):
        original = path.read_bytes()
        with Image.open(io.BytesIO(original)) as image:
            if image.format != 'PNG':
                continue
            digest = hashlib.sha256(original).hexdigest()
            if digest not in optimized:
                buf = io.BytesIO()
                options = {k: image.info[k] for k in ('icc_profile', 'exif', 'dpi', 'transparency') if k in image.info}
                image.save(buf, format='PNG', optimize=True, compress_level=9, **options)
                candidate = buf.getvalue()
                check = Image.open(io.BytesIO(candidate))
                assert check.size == image.size and check.convert('RGBA').tobytes() == image.convert('RGBA').tobytes()
                optimized[digest] = candidate if len(candidate) < len(original) else original
            candidate = optimized[digest]
            if len(candidate) < len(original):
                relative = path.relative_to(ROOT)
                backup = BACKUP / relative
                backup.parent.mkdir(parents=True, exist_ok=True)
                if not backup.exists():
                    backup.write_bytes(original)
                path.write_bytes(candidate)
                report['png'].append({'path': relative.as_posix(), 'before': len(original), 'after': len(candidate), 'size': image.size})
                print('Lossless PNG', relative, len(original), '->', len(candidate), flush=True)

manifest = json.loads((STATIC / 'state-hero/manifest.json').read_text(encoding='utf8'))
sources = [STATIC / 'state-hero' / v['file'] for entry in manifest.values() for v in entry['variants']]
sources += list((STATIC / 'simulation').glob('*.webp'))
sources += list((STATIC / 'weather').glob('*.jpg'))
sources += list((STATIC / 'header').glob('*.png'))
delivery = {}
for source in sources:
    image = Image.open(source).convert('RGB')
    buf = io.BytesIO()
    image.save(buf, format='AVIF', quality=85, speed=6, subsampling='4:4:4', max_threads=2)
    data = buf.getvalue()
    if len(data) >= source.stat().st_size * 0.92:
        report['unchanged'].append(source.relative_to(STATIC).as_posix())
        continue
    decoded = Image.open(io.BytesIO(data)).convert('RGB')
    assert decoded.size == image.size
    error = np.asarray(image, dtype=np.float32) - np.asarray(decoded, dtype=np.float32)
    mse = float(np.mean(error * error))
    psnr = 10 * math.log10(255**2 / mse) if mse else 100
    if psnr < 40:
        report['unchanged'].append(source.relative_to(STATIC).as_posix())
        continue
    name = source.stem + '-optimized.avif'
    dest = source.with_name(name)
    dest.write_bytes(data)
    relative = source.relative_to(STATIC).as_posix()
    delivery[relative] = dest.relative_to(STATIC).as_posix()
    report['delivery'].append({'source': relative, 'file': delivery[relative], 'before': source.stat().st_size, 'after': len(data), 'size': image.size, 'psnr_db': round(psnr, 2)})
    print('AVIF', relative, source.stat().st_size, '->', len(data), flush=True)

(ROOT / 'dashboard/templates/optimized_images_data.html').write_text(
    '{# Generated by tools/optimize_dashboard_images.py; original dimensions retained. #}\n'
    + '{% set optimized_images = ' + json.dumps(delivery, indent=2) + ' %}\n', encoding='utf8')
(ROOT / 'output/image-optimization-report.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf8')
print('PNG savings', sum(x['before']-x['after'] for x in report['png']), flush=True)
print('Delivery savings', sum(x['before']-x['after'] for x in report['delivery']), flush=True)
